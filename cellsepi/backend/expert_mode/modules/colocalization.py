def get_center(mask):
    coords = np.argwhere(mask)  # rows are the available axes
    center = coords.mean(axis=0) if len(coords) else None

    return center


def get_volume(mask):
    return np.sum(mask)


def get_XY_radius(mask):
    # Radius on the XY plane
    yx_mask = mask
    if mask.ndim == 3:
        yx_mask = np.max(mask, axis=0)
    return np.sqrt(np.sum(yx_mask) / np.pi)


def process_cytoplasm(cytoplasm_mask, series, channel):
    mask_ids = np.unique(cytoplasm_mask)

    cytoplasm_table = pd.DataFrame(
        columns=[
            "Cytoplasm ID", "Cytoplasm Nr", "Channel", "Series",
            "Cytoplasm X", "Cytoplasm Y", "Cytoplasm Z",
            "Cytoplasm Radius", "Cytoplasm Volume"
        ]
    )

    prop_dicts = []
    for mask_id in mask_ids:
        if mask_id == 0:
            # Skip Background
            continue
        mask = cytoplasm_mask == mask_id

        cytoplasm_id = f"{series}-{channel}-{mask_id}"

        center = get_center(mask)
        radius = get_XY_radius(mask)
        volume = get_volume(mask)

        prop_dict = {
            "Cytoplasm ID": cytoplasm_id,
            "Cytoplasm Nr": mask_id,
            "Channel": channel,
            "Series": series,
            "Cytoplasm X": center[-1],
            "Cytoplasm Y": center[-2],
            "Cytoplasm Z": center[-3] if len(center) == 3 else None,
            "Cytoplasm Radius": radius,
            "Cytoplasm Volume": volume,
        }
        prop_dicts.append(prop_dict)
    df = pd.DataFrame(prop_dicts)
    return df
